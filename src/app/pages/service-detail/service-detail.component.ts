@Component({
    selector: 'app-service-detail',
    standalone: true,
    imports: [CommonModule, RouterLink, PageHeroComponent],
    templateUrl: './service-detail.component.html',
    styleUrl: './service-detail.component.scss',
})
export class ServiceDetailComponent implements OnInit {
    service: ServiceItem | null = null;
    detail: ServiceDetail | null = null;
    otherServices: ServiceItem[] = [];

    constructor(private route: ActivatedRoute) { }

    ngOnInit(): void {
        this.route.params.subscribe((params) => {
            const slug = params['slug'];
            const base = SERVICES_DATA.find((s) => s.slug === slug);
            const extra = SERVICE_DETAILS[slug];

            if (base && extra) {
                this.service = base;
                this.detail = { ...base, ...extra };
                this.otherServices = SERVICES_DATA.filter((s) => s.slug !== slug);
            }
        });
    }
}
